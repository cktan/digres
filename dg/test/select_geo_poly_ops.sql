-- Verify path and polygon, whose operations ty does (ty/DESIGN.md
-- section 23).
-- 1. path: area, length, the number of points, + - * / with a point.
-- 2. path against path and point: meet, distance, on.
-- 3. polygon: the position operators, same, overlap, contain, distance.
-- 4. polygon against point and circle, the center, and the circle of one.
-- (Errors are server.sh's: a run stops at its first.)

