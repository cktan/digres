-- Verify line and lseg, and their operators with point and box, whose
-- operations ty does (ty/DESIGN.md section 21).
-- 1. line: intersect, parallel, perpendicular, equal, distance, meet point.
-- 2. lseg: length, the order by length, the tests of direction, center, meet.
-- 3. point against line, lseg and box: distance, closest point, on.
-- 4. lseg against line and box, and line against box: distance, closest
--    point, on, intersect.
-- (Errors are server.sh's: a run stops at its first.)

SELECT a, ?| a AS vert, ?- a AS horiz
FROM (VALUES
  (0, '{1,2,3}'::line),
  (1, '{1,-1,0}'),
  (2, '{0,1,-2}'),
  (3, '{1,0,-3}'),
  (4, '{2,4,6}'),
  (5, '{-2,1,0}'),
  (6, '{1,1,1}'),
  (7, '{3,4,5}'),
  (8, '{-1,0,2}'),
  (9, '{1e-7,1,1}'),
  (10, '{NaN,1,0}')) a(ia, a) ORDER BY ia;

